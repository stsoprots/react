// Оголошуємо та експортуємо інтерфейс IPost для типізації структури даних поста
export interface IPost {
    // Числовий ідентифікатор користувача (автора), якому належить публікація
    userId: number;
    // Унікальний числовий ідентифікатор самого поста
    id: number;
    // Рядкове поле з заголовком публікації
    title: string;
    // Рядкове поле з основним текстом (тілом) поста
    body: string;

}