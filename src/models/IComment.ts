// Оголошуємо та експортуємо інтерфейс IComment для типізації структури даних коментаря
export interface IComment {
    // Числовий ідентифікатор поста, до якого належить цей коментар
    postId: number;
    // Унікальний числовий ідентифікатор самого коментаря
    id: number;
    // Рядкове поле з назвою коментаря або заголовком повідомлення
    name: string;
    // Рядкове поле з основним текстом (тілом) коментаря
    body: string;
}